/** 근거 셀에서 [CODE] 추출. 괄호가 없으면 본문에서 알려진 코드 토큰을 찾는다. */
export function extractSources(text) {
  const found = [];
  const re = /\[([^\]]+)\]/g;
  let m;
  while ((m = re.exec(text))) {
    const inner = m[1].trim();
    if (inner.startsWith('RMRS 색상환')) { found.push('RMRS 색상환'); continue; }
    const first = inner.split(/[\s'"]/)[0];
    if (first) found.push(first);
  }
  if (found.length === 0) {
    // 괄호 없는 매체 언급: 코드 토큰이 단어로 등장하면 채택
    const plain = text;
    const tokens = ['FB1', 'FB2', 'FB3', 'FB4', 'GG', 'MM', 'HB', 'PM', 'MF', 'AtG1', 'AtG2', 'AtG3', 'AtG4', 'Dapp', 'MSR', 'MRP', 'Allure', 'StyleGF', 'VK2', 'WH1', 'WH2', 'RMRS2', 'PS2'];
    for (const t of tokens) {
      if (new RegExp(`(^|[^A-Za-z0-9])${t}([^A-Za-z0-9]|$)`).test(plain)) found.push(t);
    }
    if (/Vogue Korea/.test(plain)) found.push('VK1');
    if (/PS도/.test(plain)) found.push('PS2');
  }
  return [...new Set(found)];
}
